#!/usr/bin/env python3
"""The reserved words of the grammars: the words that the Catala compiler never
accepts as identifiers.

The candidates are the words of the strings of the compiler's lexer tables
(the MS_ macros of compiler/surface/lexer_<lang>.cppo.ml) that have the form
of an identifier. Each is given to the compiler as the name of a declaration
("declaration <word> content integer equals 1", in the language):

- a syntax error means that the lexer lexes the word as a keyword, such as
  "scope" or "year";
- "Reserved builtin name" means that the word is a built-in function, such
  as "decimal" or "round": the lexer lexes it as an identifier, but the
  parser takes it as the built-in wherever an expression may be one, and
  every binding of the name is rejected.

Both are reserved. The first word of a multi-word keyword, such as "depends"
in "depends on", is reserved only if it is a keyword on its own.

Usage:
  reserved_words.py update --catala BIN --src DIR [--langs LANG...]
      rewrites the reserved_words table of grammar.js
  reserved_words.py check --catala BIN --src DIR [--abi15 DIR] [--langs LANG...]
      fails if the table of grammar.js differs from the compiler's keywords
      and, with --abi15, if an ABI 15 parser generated in DIR/catala_<lang>
      does not reject exactly those words as the name of a declaration

BIN is a catala binary and DIR a checkout of the compiler with the lexer
tables of every language. The languages default to en, fr and pl.
"""
import argparse, json, os, re, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
GRAMMAR = os.path.join(HERE, "grammar.js")
BEGIN = "// BEGIN reserved_words"
END = "// END reserved_words"


def lexer_table(src, lang):
    """The MS_ macros of the language's lexer: name -> string."""
    path = os.path.join(src, "compiler", "surface", f"lexer_{lang}.cppo.ml")
    table = {}
    for line in open(path, encoding="utf-8"):
        m = re.match(r'\s*#define\s+MS_(\w+)\s+"((?:[^"\\]|\\.)*)"\s*$', line)
        if m:
            table[m.group(1)] = m.group(2)
    return table


def is_identifier(word):
    """The form of an identifier (LIDENT): a lowercase letter, then letters,
    digits, '_' or "'"."""
    return word[0].islower() and all(c.isalnum() or c in "_'" for c in word)


def declaration(table, name):
    return (f"```catala\n{table['DECLARATION']} {name} {table['CONTENT']} "
            f"{table['INTEGER']} {table['DEFINED_AS']} 1\n```\n")


def compiler_keywords(catala, src, lang):
    table = lexer_table(src, lang)
    candidates = sorted({w for s in table.values() for w in s.split()
                         if is_identifier(w)})
    work = tempfile.mkdtemp()
    path = os.path.join(work, f"k.catala_{lang}")
    keywords = []
    for word in candidates:
        with open(path, "w", encoding="utf-8") as f:
            f.write(declaration(table, word))
        r = subprocess.run([catala, "typecheck", "--no-stdlib", path],
                           capture_output=True, text=True,
                           env={**os.environ, "NO_COLOR": "1"})
        if r.returncode == 0:
            continue
        if re.search(r"Syntax error|Parsing error|Lexing error|"
                     r"Reserved builtin name", r.stderr):
            keywords.append(word)
        else:
            sys.exit(f"{lang}: unexpected error for {word!r}:\n{r.stderr}")
    return table, candidates, keywords


def render(sets):
    lines = [BEGIN + " (generated by reserved_words.py from the",
             "// compiler's lexer tables; do not edit)",
             "const reserved_words = {"]
    for lang, words in sets.items():
        lines.append(f"  {lang}: [")
        line = "   "
        for w in words:
            item = " " + json.dumps(w, ensure_ascii=False) + ","
            if len(line) + len(item) > 78:
                lines.append(line)
                line = "   "
            line += item
        lines.append(line)
        lines.append("  ],")
    lines += ["}", END]
    return "\n".join(lines)


def grammar_block():
    text = open(GRAMMAR, encoding="utf-8").read()
    start, end = text.index(BEGIN), text.index(END) + len(END)
    return text, start, end


def grammar_sets():
    text, start, end = grammar_block()
    body = text[start:end]
    return {m.group(1): json.loads("[" + m.group(2).strip().rstrip(",") + "]")
            for m in re.finditer(r"^  (\w+): \[(.*?)^  \],", body, re.S | re.M)}


def parses_as_error(parser_dir, text, rebuild=False):
    """Whether the parser in parser_dir gives an ERROR or MISSING node. The
    tree-sitter CLI caches a grammar's library by name only, so the first
    parse of each directory rebuilds it."""
    with tempfile.NamedTemporaryFile("w", suffix=".txt", delete=False,
                                     encoding="utf-8") as f:
        f.write(text)
    r = subprocess.run(["tree-sitter", "parse", *(["--rebuild"] if rebuild else []),
                        f.name], cwd=parser_dir, capture_output=True, text=True)
    return re.search(r"\b(ERROR|MISSING)\b", r.stdout) is not None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("command", choices=["update", "check"])
    ap.add_argument("--catala", required=True)
    ap.add_argument("--src", required=True)
    ap.add_argument("--abi15")
    ap.add_argument("--langs", nargs="+", default=["en", "fr", "pl"])
    args = ap.parse_args()
    derived = {}
    for lang in args.langs:
        derived[lang] = compiler_keywords(args.catala, args.src, lang)
    sets = {lang: kw for lang, (_, _, kw) in derived.items()}
    if args.command == "update":
        text, start, end = grammar_block()
        old = grammar_sets()
        old.update(sets)
        with open(GRAMMAR, "w", encoding="utf-8") as f:
            f.write(text[:start] + render(old) + text[end:])
        for lang, kw in sets.items():
            print(f"{lang}: {len(kw)} reserved words")
        return
    failed = False
    committed = grammar_sets()
    for lang, (table, candidates, keywords) in derived.items():
        if committed.get(lang) != keywords:
            failed = True
            missing = sorted(set(keywords) - set(committed.get(lang, [])))
            extra = sorted(set(committed.get(lang, [])) - set(keywords))
            print(f"{lang}: grammar.js differs from the compiler's keywords: "
                  f"missing {missing}, not keywords {extra}")
        else:
            print(f"{lang}: grammar.js reserves the compiler's {len(keywords)} "
                  f"keywords ({len(candidates)} candidate words)")
        if args.abi15:
            parser_dir = os.path.join(args.abi15, f"catala_{lang}")
            wrong = [w for i, w in enumerate(candidates)
                     if parses_as_error(parser_dir, declaration(table, w), i == 0)
                     != (w in keywords)]
            if wrong:
                failed = True
                print(f"{lang}: the ABI 15 parser disagrees with the compiler "
                      f"on {wrong}")
            else:
                print(f"{lang}: the ABI 15 parser rejects exactly those "
                      f"keywords as a declaration name")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
